import * as THREE from "three";
import { OBJLoader } from "three/addons/loaders/OBJLoader.js";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { MeshoptDecoder } from "three/addons/libs/meshopt_decoder.module.js";

const objLoader = new OBJLoader();
const gltfLoader = new GLTFLoader();
gltfLoader.setMeshoptDecoder(MeshoptDecoder);
const texLoader = new THREE.TextureLoader();

// Build a URL-safe path under data/. Encodes the folder name (which often
// contains spaces / underscores / non-ASCII) and transparently rewrites to
// the optimized assets produced by tools/preprocess/:
//   .obj            → data/optimized/<folder>/models/*.glb (Meshopt-compressed)
//   .png/.jpg/.jpeg → data/optimized/<folder>/textures/*.webp
// Callers keep using the original logical paths (e.g. "models/model_0.obj");
// the loader picks the right format. To bypass the rewrite (e.g. a one-off
// raw asset under data/photo), pass `{ raw: true }`.
export function dataURL(folder, file, opts = {}) {
    if (opts.raw) return `/data/${encodeURI(folder)}/${file}`;
    const rewritten = file.replace(/\.(obj)$/i, ".glb")
                          .replace(/\.(png|jpe?g)$/i, ".webp");
    return `/data/optimized/${encodeURI(folder)}/${rewritten}`;
}

// asset-meta.json is generated by scripts/build-asset-meta.mjs. We fetch it
// once and cache the result so the metadata-aware loaders (loadFolder)
// can decide rotation/scale without trial-and-error.
let metaPromise = null;
export function loadAssetMeta() {
    if (!metaPromise) {
        metaPromise = fetch("/data/asset-meta.json")
            .then((r) => (r.ok ? r.json() : {}))
            .catch(() => ({}));
    }
    return metaPromise;
}

// Load every part under data/<folder>/models, apply Z→Y up rotation if the
// metadata says the source is Z-up, and scale to the suggested real-world
// size. Returns a Group with the assembled+oriented model recentered +
// dropped to floor — ready to position via wrap.position.set().
export async function loadFolder(folder, opts = {}) {
    const meta = await loadAssetMeta();
    const folderMeta = meta[folder];
    if (!folderMeta) {
        console.warn(`assets: no metadata for "${folder}"`);
        return null;
    }
    const onMesh = opts.onMesh;
    const partFiles =
        opts.parts || folderMeta.parts.map((p) => p.file);
    const groups = await Promise.all(
        partFiles.map((f) => loadOBJ(dataURL(folder, f), onMesh)),
    );
    const inner = new THREE.Group();
    for (const g of groups) if (g) inner.add(g);
    if (folderMeta.suggestedUp === "z") inner.rotation.x = -Math.PI / 2;
    const wrap = new THREE.Group();
    wrap.add(inner);
    const target = opts.targetSize ?? folderMeta.targetSize;
    const fit = target ? fitToFloor(wrap, target) : { size: new THREE.Vector3() };
    // Tag the wrapper so the scene exporter can recognise asset-loaded models
    // and emit them as `{kind:"asset", folder}` entities instead of dumping
    // every triangle as a primitive.
    wrap.userData.assetFolder = folder;
    if (target != null) wrap.userData.targetSize = target;
    return { wrap, size: fit.size, meta: folderMeta };
}

// --- async-load progress tracking -------------------------------------
// Lightweight counter the welcome page uses to drive its progress UI.
// Anything that goes through `loadOBJ` / `loadTexture` increments at start
// and decrements on resolve (or fail). Pages can subscribe via
// `onLoadProgress` to react when work begins or finishes.
let _loadsStarted = 0;
let _loadsFinished = 0;
const _loadListeners = new Set();
function _emit(label) {
    for (const cb of _loadListeners) {
        try { cb({ started: _loadsStarted, finished: _loadsFinished, label }); }
        catch { /* listener bug shouldn't break loading */ }
    }
}
export function getLoadStats() {
    return { started: _loadsStarted, finished: _loadsFinished };
}
export function onLoadProgress(cb) {
    _loadListeners.add(cb);
    return () => _loadListeners.delete(cb);
}
function _track(url, promise) {
    _loadsStarted++;
    _emit(url);
    return promise.finally(() => {
        _loadsFinished++;
        _emit(url);
    });
}

// Load a single mesh. Dispatches on extension: .glb uses GLTFLoader (with
// Meshopt decompression), anything else falls back to OBJLoader. The legacy
// name is kept so existing callsites don't have to change.
export function loadOBJ(url, onMesh) {
    const isGLB = /\.glb$/i.test(url);
    return _track(url, new Promise((resolve) => {
        const onLoad = (result) => {
            const g = isGLB ? result.scene : result;
            if (onMesh)
                g.traverse((o) => {
                    if (o.isMesh) onMesh(o);
                });
            resolve(g);
        };
        const loader = isGLB ? gltfLoader : objLoader;
        loader.load(url, onLoad, undefined, () => resolve(null));
    }));
}

export async function loadOBJBatch(urls, onMesh) {
    const groups = await Promise.all(urls.map((u) => loadOBJ(u, onMesh)));
    const wrap = new THREE.Group();
    for (const g of groups) if (g) wrap.add(g);
    return wrap;
}

// Load a 2D texture. Defaults to sRGB (correct for color/albedo/emissive
// maps). Pass `{ colorSpace: THREE.NoColorSpace }` for non-color data —
// normal, roughness, metallic, AO, height — otherwise three.js will apply
// an sRGB→linear conversion on each fetch and the lighting will be wrong
// (normals come out too contrasty, roughness reads as too smooth).
export function loadTexture(url, opts = {}) {
    return _track(url, new Promise((resolve) => {
        texLoader.load(
            url,
            (t) => {
                t.colorSpace = opts.colorSpace ?? THREE.SRGBColorSpace;
                resolve(t);
            },
            undefined,
            () => resolve(null),
        );
    }));
}

// Centre a group's bounding box at its origin and scale it to a target
// max-dimension. Uses the `outer.scale + inner.position` pattern so the
// outer group's `position` and `rotation` remain free for the caller to
// set. The naive approach (translate by -center, then scale outer) is a
// classic three.js footgun: scale applies to children before the parent's
// translation, leaving a residual offset of `center * (s - 1)`.
//
// Use this for wall plaques, hanging signs, anything that should be
// centered (rather than floor-anchored — for floor-anchored, use
// fitToFloor). Returns { size } in world units (post-scale).
export function centerScale(group, targetMaxDim = null) {
    const bbox = new THREE.Box3().setFromObject(group);
    if (bbox.isEmpty()) return { size: new THREE.Vector3() };
    const size = new THREE.Vector3();
    const center = new THREE.Vector3();
    bbox.getSize(size);
    bbox.getCenter(center);
    let s = 1;
    if (targetMaxDim) {
        const maxDim = Math.max(size.x, size.y, size.z);
        if (maxDim > 0) s = targetMaxDim / maxDim;
    }
    const inner = new THREE.Group();
    inner.name = "centerInner";
    while (group.children.length) inner.add(group.children[0]);
    inner.position.set(-center.x, -center.y, -center.z);
    group.add(inner);
    group.scale.setScalar(s);
    return { size: size.multiplyScalar(s) };
}

// Recenter and scale a group so its xz bbox center is at (0, 0) and y starts
// at 0. If targetMaxDim is provided, scale uniformly so the largest of
// {x,y,z} matches that dim. Returns the post-scale size for downstream use.
// Recenter the model and drop it to the floor, then scale to a target
// size. We rehome existing children into a private inner group that
// carries the centering offset — that way the *outer* group's position
// and rotation are still free for the caller to set without losing the
// centering. Returns { size } in world units (post-scale).
export function fitToFloor(group, targetMaxDim = null) {
    const bbox = new THREE.Box3().setFromObject(group);
    if (bbox.isEmpty()) return { size: new THREE.Vector3() };
    const size = new THREE.Vector3();
    const center = new THREE.Vector3();
    bbox.getSize(size);
    bbox.getCenter(center);
    let s = 1;
    if (targetMaxDim) {
        const maxDim = Math.max(size.x, size.y, size.z);
        if (maxDim > 0) s = targetMaxDim / maxDim;
    }
    // Move the existing children into an inner group whose position is the
    // centering offset. The outer (passed-in) group only gets a scale; its
    // own position/rotation are untouched.
    const inner = new THREE.Group();
    inner.name = "fitInner";
    while (group.children.length) inner.add(group.children[0]);
    inner.position.set(-center.x, -bbox.min.y, -center.z);
    group.add(inner);
    group.scale.setScalar(s);
    return { size: size.multiplyScalar(s) };
}
